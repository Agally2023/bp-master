import { h, clear, toast } from '../util.js?v=202611270907';
import { db } from '../db.js?v=202611270907';

const P = () => window.bpmPrefs;
const CFG = window.BPM_CONFIG || {};

// A row of mutually exclusive buttons bound to one preference.
function seg(key, options, onChange) {
  const box = h('div', { class: 'seg', role: 'group' });
  const paint = () => [...box.children].forEach(b => b.setAttribute('aria-pressed', String(String(P().get()[key]) === b.dataset.v)));
  for (const [v, label] of options) box.append(h('button', { type: 'button', 'data-v': v, onclick: () => { P().set(key, typeof options[0][0] === 'number' ? Number(v) : v); paint(); onChange?.(); } }, label));
  paint(); return box;
}
const row = (label, hint, control) => h('div', { class: 'set-row' }, h('div', {}, h('div', { class: 'lbl' }, label), hint ? h('div', { class: 'hint' }, hint) : null), control);
const card = (title, ...kids) => h('div', { class: 'card' }, h('h2', {}, title), ...kids);

export async function render({ view }) {
  const u = db.user || {};
  const themeCard = (() => {
    const box = h('div', { class: 'prev' });
    const paint = () => [...box.children].forEach(b => b.setAttribute('aria-pressed', String(P().get().theme === b.dataset.v)));
    for (const [v, name, note] of [['auto', 'Auto', 'Follows your device and, where supported, the light in the room'], ['light', 'Normal', 'The standard Victory Farms look: bright, for daylight and print-like reading'], ['amoled', 'AMOLED', 'True black: saves battery on OLED screens and is easy on the eyes at night']])
      box.append(h('button', { type: 'button', 'data-v': v, onclick: () => { P().set('theme', v); paint(); } }, h('div', { class: 'sw t-' + v }, h('i', { style: 'height:40%' }), h('i', { style: 'height:70%' }), h('i', { style: 'height:55%' })), h('b', {}, name), h('div', { class: 'hint' }, note)));
    paint(); return box;
  })();

  const appearance = card('Appearance', themeCard,
    row('Text brightness (AMOLED)', 'Auto dims the text in a dark room and brightens it in daylight when the device reports its light level; otherwise it dims a little at night.', seg('bright', [['auto', 'Auto'], ['dim', 'Dim'], ['normal', 'Normal'], ['bright', 'Bright']])),
    row('Text size', 'Scales the whole app.', seg('size', [['s', 'Small'], ['m', 'Default'], ['l', 'Large'], ['xl', 'Extra large']])),
    row('Density', 'Compact fits more rows and charts on screen.', seg('density', [['comfortable', 'Comfortable'], ['compact', 'Compact']])),
    row('Motion', 'Turn off transitions and animations.', seg('motion', [['full', 'Full'], ['reduce', 'Reduced']])));

  const session = card('Session & security',
    row('Automatic sign-out', 'Sign out after this long without activity on this device.', seg('idle', [[5, '5 min'], [15, '15 min'], [30, '30 min'], [60, '60 min']], () => toast('Sign-out time updated'))));

  // account: name, role, password
  const pw1 = h('input', { type: 'password', autocomplete: 'new-password', placeholder: 'New password (10+ characters)', 'aria-label': 'New password' });
  const pw2 = h('input', { type: 'password', autocomplete: 'new-password', placeholder: 'Repeat new password', 'aria-label': 'Repeat new password' });
  const msg = h('div', { class: 'muted', role: 'status' });
  const change = h('button', { class: 'btn', type: 'button', onclick: async () => {
    if (pw1.value.length < 10) { msg.textContent = 'Use at least 10 characters.'; return; }
    if (pw1.value !== pw2.value) { msg.textContent = 'The two passwords do not match.'; return; }
    if (db.mode !== 'live') { msg.textContent = 'Demo mode: no real account to change.'; return; }
    change.disabled = true;
    try { await db.updatePassword(pw1.value); toast('Password changed. Please sign in again.'); location.reload(); }
    catch (e) { msg.textContent = 'Could not change the password: ' + (e.message || e); change.disabled = false; }
  } }, 'Change password');
  const account = card('Account',
    row('Name', null, h('span', {}, u.name || '–')), row('Email', null, h('span', {}, u.email || '–')),
    row('Role', { admin: 'Administrator: manages users, approves and exports reports', auditor: 'Auditor: enters and imports data', reviewer: 'Reviewer: read only' }[u.role] || null, h('span', { class: 'pill' }, u.role || '–')),
    h('div', { class: 'set-row' }, h('div', { style: 'display:grid;gap:8px;min-width:min(320px,100%)' }, h('div', { class: 'lbl' }, 'Change password'), pw1, pw2, msg), change));

  const about = card('About & data',
    row('Mode', db.mode === 'live' ? 'Connected to your database.' : 'Demo mode: nothing is saved.', h('span', { class: 'pill ' + (db.mode === 'live' ? 'ok' : 'warn') }, db.mode === 'live' ? 'Live' : 'Demo')),
    row('PowerPoint service', CFG.REPORT_API_URL ? 'Reports are generated by this service (an admin exports approved reports).' : 'Not configured.', h('span', { class: 'muted' }, CFG.REPORT_API_URL ? new URL(CFG.REPORT_API_URL).host : '–')),
    row('Reset this device\'s settings', 'Theme, text size, density, motion and sign-out time go back to the defaults. Your data is not touched.', h('button', { class: 'btn sec', type: 'button', onclick: () => { P().reset(); toast('Settings reset'); render2(); } }, 'Reset settings')));

  const QC = 'https://victoryfarmsltd.sharepoint.com/sites/AquaData/Shared%20Documents/Aqua%20Quality%20Control/';
  const folder = (name, note) => row(name, note, h('a', { class: 'btn sec', href: QC + encodeURIComponent(name), target: '_blank', rel: 'noopener noreferrer' }, 'Open'));
  const links = card('Farm Aqua Reports - Quality Control',
    folder('BP Reports', 'Weekly Best Practice report decks (export from Reports, then save here).'),
    folder('BP Pond Files', 'Pond audit workbooks: flipping, broodstock stocking density and sex ratio.'),
    folder('BP Incubation Files', 'Incubation audit workbooks: workstations, stocking, parasitology, 3-day recounts.'),
    folder('BP Other Files', 'Other Best Practice files.'));
  let srcs = []; try { srcs = await db.load('sync_sources') || []; } catch { /* table not present in demo mode */ }
  const ago = t => { if (!t) return 'never'; const m = Math.round((Date.now() - new Date(t)) / 60000); return m < 2 ? 'just now' : m < 90 ? m + ' min ago' : m < 2880 ? Math.round(m / 60) + ' h ago' : Math.round(m / 1440) + ' days ago'; };
  const sync = card('Automatic updates from SharePoint',
    ...(srcs.length ? srcs.map(x => row(x.label, `${x.file_name || ''} - latest data ${x.latest_data_date || 'not loaded yet'}. ${x.last_message || 'Waiting for the first sync.'}`,
      h('span', { class: 'pill' }, x.last_status === 'ok' ? 'Updated ' + ago(x.last_run) : x.last_status === 'unchanged' ? 'Up to date (' + ago(x.last_run) + ')' : x.last_status === 'error' ? 'Error' : 'Not started')))
      : [row('Not set up', 'The sync service has no sources in this mode.', h('span', { class: 'pill' }, '-'))]));
  const wrap = h('div', { class: 'set-grid' }); view.append(wrap);
  const render2 = () => { clear(view); render({ view }); };
  wrap.append(appearance, session, account, links, sync, about);
}
